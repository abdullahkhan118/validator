import com.vanniktech.maven.publish.GradlePlugin
import com.vanniktech.maven.publish.JavadocJar

plugins {
    alias(libs.plugins.kotlin.jvm)
    `java-gradle-plugin`
    alias(libs.plugins.maven.publish)
}

repositories {
    mavenCentral()
}

dependencies {
    // Provided by the consumer's build, which applies the Kotlin Gradle plugin.
    compileOnly(libs.kotlin.gradle.plugin.api)
}

kotlin {
    jvmToolchain(17)
}

gradlePlugin {
    plugins {
        create("validator") {
            id = "io.github.abdullahkhan118.validator"
            implementationClass = "io.github.abdullahkhan118.validator.gradle.ValidatorGradlePlugin"
            displayName = "Validator"
            description = providers.gradleProperty("POM_DESCRIPTION").get()
        }
    }
}

// The plugin adds the annotations and the compiler plugin of ITS OWN version, and the compiler plugin only works
// with the Kotlin version it was built with: bake both versions into the plugin as constants.
val generateBuildConfig by tasks.registering {
    val group = providers.gradleProperty("GROUP")
    val version = providers.gradleProperty("VERSION_NAME")
    val kotlinVersion = libs.versions.kotlin
    val output = layout.buildDirectory.dir("generated/buildConfig")
    inputs.property("group", group)
    inputs.property("version", version)
    inputs.property("kotlinVersion", kotlinVersion)
    outputs.dir(output)
    doLast {
        val file = output.get().file("io/github/abdullahkhan118/validator/gradle/BuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package io.github.abdullahkhan118.validator.gradle
            |
            |// Generated by the gradle-plugin build (generateBuildConfig). Don't edit.
            |internal object BuildConfig {
            |    const val GROUP = "${group.get()}"
            |    const val VERSION = "${version.get()}"
            |    const val KOTLIN_VERSION = "${kotlinVersion.get()}"
            |}
            |""".trimMargin(),
        )
    }
}
kotlin.sourceSets.main { kotlin.srcDir(generateBuildConfig) }

mavenPublishing {
    configure(GradlePlugin(javadocJar = JavadocJar.Empty(), sourcesJar = true))
    publishToMavenCentral()
    // Maven Central requires signatures; local publishing (publishToMavenLocal) works without a key.
    if (providers.gradleProperty("signingInMemoryKey").isPresent) signAllPublications()
}
